class FakeResponse:
    def __init__(self, result: str = "", exit_code: int = 0) -> None:
        self.result = result
        self.exit_code = exit_code


class FakeSandbox:
    """One sandbox of the fake client: `fs` and `process` are the sandbox itself."""

    def __init__(self, client, index: int, params) -> None:
        self.client = client
        self.index = index
        self.id = f"sb-{index}"
        self.params = params
        self.uploads: dict[str, bytes] = {}
        self.commands: list[tuple[str, str | None]] = []
        self.polls = 0
        self.deleted = False
        self.fs = self
        self.process = self

    def upload_file(self, src, dst: str, timeout: int = 1800) -> None:
        assert isinstance(src, bytes)
        self.uploads[dst] = src

    def exec(
        self, command: str, cwd: str | None = None, env=None, timeout: int | None = None
    ) -> FakeResponse:
        self.commands.append((command, cwd))
        if self.client.fail_on and self.client.fail_on in command:
            raise RuntimeError(f"exec failed: {command}")
        if self.client.interrupt_on and self.client.interrupt_on in command:
            raise KeyboardInterrupt
        if "progress.csv" in command:
            self.polls += 1
            rows = self.client.progress_text(self).splitlines()
            return FakeResponse(rows[min(self.polls, len(rows)) - 1])
        if "summary.json" in command:
            if self.index in self.client.dead:
                return FakeResponse("dead")
            return FakeResponse("done" if self.polls >= self.client.polls_until_done else "running")
        if "train.log" in command:
            return FakeResponse("Traceback ...\nerror: reward() raised ZeroDivisionError at step 3")
        return FakeResponse("")

    def download_file(self, path: str) -> bytes:
        name = path.rsplit("/", 1)[-1]
        files = self.client.files_for(self)
        if name not in files:
            raise FileNotFoundError(path)
        return files[name]

    def delete(self, timeout: float | None = 60, wait: bool = False) -> None:
        self.deleted = True


class FakeDaytona:
    def __init__(self, rates, means, *, dead=(), fail_on=None, interrupt_on=None, polls_until_done=3) -> None:
        self.rates = list(rates)
        self.means = list(means)
        self.dead = set(dead)
        self.fail_on = fail_on
        self.interrupt_on = interrupt_on
        self.polls_until_done = polls_until_done
        self.sandboxes: list[FakeSandbox] = []

    def create(self, params, *, timeout: float = 60, on_snapshot_create_logs=None) -> FakeSandbox:
        assert len(self.sandboxes) < 4, "a fifth RL sandbox was requested"
        sandbox = FakeSandbox(self, len(self.sandboxes) + 1, params)
        self.sandboxes.append(sandbox)
        return sandbox

    def progress_text(self, sandbox: FakeSandbox) -> str:
        rate = self.rates[sandbox.index - 1]
        return f"step,mean_reward,success_rate\n20000,-10.5,0.1\n40000,5.0,{rate}\n"

    def files_for(self, sandbox: FakeSandbox) -> dict[str, bytes]:
        if sandbox.index in self.dead:
            return {"train.log": b"error: reward() raised ZeroDivisionError at step 3"}
        rate = self.rates[sandbox.index - 1]
        summary = {
            "episodes": 100,
            "successes": int(round(100 * rate)),
            "success_rate": rate,
            "mean_steps_to_success": self.means[sandbox.index - 1],
            "falls": 0,
            "mean_final_dist": 0.02,
            "steps": 40000,
        }
        return {
            "policy.zip": b"PK-policy-%d" % sandbox.index,
            "progress.csv": self.progress_text(sandbox).encode("utf-8"),
            "summary.json": json.dumps(summary).encode("utf-8"),
            "train.log": b"training log",
        }


