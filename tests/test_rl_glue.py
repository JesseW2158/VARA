class StubPolicy:
    """A constant-action policy that records every observation it was given."""

    def __init__(self, action) -> None:
        self.action = np.asarray(action, dtype=np.float32)
        self.observations: list[np.ndarray] = []

    def predict(self, obs, deterministic: bool = True):
        assert deterministic
        self.observations.append(np.array(obs, dtype=np.float64))
        return self.action.copy(), None


class UpwardPolicy(StubPolicy):
    """Pushes whichever single joint raises the tip most (2 degrees per step)."""

    def __init__(self) -> None:
        super().__init__([0.0, 0.0, 0.0, 0.0])

    def predict(self, obs, deterministic: bool = True):
        self.observations.append(np.array(obs, dtype=np.float64))
        q = np.array(obs[:5], dtype=np.float64)
        z0 = ik.fk_tip(q)[2]
        best, action = -1.0, np.zeros(4, dtype=np.float32)
        for j in range(4):
            for sign in (-1.0, 1.0):
                trial = q.copy()
                trial[j] += sign * he.MAX_STEP_RAD
                gain = ik.fk_tip(trial)[2] - z0
                if gain > best:
                    best, action = gain, np.eye(4, dtype=np.float32)[j] * sign
        return action, None


