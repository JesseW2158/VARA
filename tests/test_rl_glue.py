def test_write_rewards_retries_a_rejected_variant_once(tmp_path, monkeypatch):
    monkeypatch.setenv("FAKE_LLM", "1")
    calls: list[str | None] = []
    real_chat = wr.chat

    def flaky_chat(messages, model, *args, **kwargs):
        calls.append(kwargs.get("key"))
        reply = real_chat(messages, model, *args, **kwargs)
        if len(calls) == 1:  # the first reply carries a bad second block
            block = extract_code_blocks(reply)[1]
            assert block in reply
            reply = reply.replace(block, block.replace("import math", "import os"))
        else:
            assert messages[-1]["role"] == "user" and "Variant 2" in messages[-1]["content"]
            assert messages[-2]["role"] == "assistant"
        return reply

    monkeypatch.setattr(wr, "chat", flaky_chat)
    run_dir = tmp_path / "run"
    paths = wr.write_rewards(out_dir=tmp_path / "out", task_dir=run_dir, task_id=None)
    assert calls == [None, "variant_2"]
    assert [p.name for p in paths] == [f"variant_{k}.py" for k in range(1, 5)]
    assert split_header(paths[1].read_text(encoding="utf-8"))[1] == fixture_source(2).strip("\n") + "\n"
    problems = json.loads((run_dir / "problems.json").read_text(encoding="utf-8"))
    assert list(problems) == ["variant_2"] and any("import" in p for p in problems["variant_2"])
    retry = (run_dir / "retry_2.md").read_text(encoding="utf-8")
    assert "Variant 2" in retry and wr.SHAPING_IDEAS[1] in retry and "Return one Python code block" in retry
    manifest = json.loads((run_dir / "variants.json").read_text(encoding="utf-8"))
    assert [v["attempts"] for v in manifest["variants"]] == [1, 2, 1, 1]


