def test_run_policy_builds_the_observation_from_the_scene_and_the_driver():
    cfg = yaml.safe_load((ROOT / "config" / "scene.yaml").read_text(encoding="utf-8"))
    zone = (cfg["zones"]["handoff"]["x"], cfg["zones"]["handoff"]["y"], cfg["zones"]["handoff"]["z"])
    assert pr.handoff_zone(None) == zone and pr.ceiling_z() == cfg["workspace"]["z"][1]
    driver = FakeDriver()
    policy = StubPolicy([2.0, -0.5, 0.0, 0.0])
    assert pr.run_policy(driver, lambda: None, "unused.zip", timeout=2 * he.DT, policy=policy) is False
    first, second = policy.observations
    home = np.array(ik.home_q())
    assert first.shape == (16,) and np.allclose(first[12:15], zone)
    assert np.allclose(first[:5], home) and np.all(first[5:9] == 0.0)
    assert np.allclose(first[9:12], ik.fk_tip(home), atol=1e-6)
    assert abs(first[15] - math.dist(ik.fk_tip(home), zone)) < 1e-5
    assert np.allclose(second[5:9], [1.0, -0.5, 0.0, 0.0])  # the clipped action of the previous step
    assert np.allclose(second[:5], driver.commands[0][0])  # the fake arm followed the command
    assert np.allclose(driver.commands[0][0][:2], home[:2] + [he.MAX_STEP_RAD, -0.5 * he.MAX_STEP_RAD])
    # a seen hand -> 5 cm above it; an unseen one -> the zone; a scene zone overrides the config
    hand = {"marker": 40, "x": 0.25, "y": 0.05, "z": 0.03, "seen": True}
    policy = StubPolicy([0.0, 0.0, 0.0, 0.0])
    pr.run_policy(FakeDriver(), lambda: {"hand": hand}, "unused.zip", timeout=he.DT, policy=policy)
    assert np.allclose(policy.observations[-1][12:15], [0.25, 0.05, 0.08])
    pr.run_policy(
        FakeDriver(), lambda: {"hand": {**hand, "seen": False}}, "unused.zip", timeout=he.DT, policy=policy
    )
    assert np.allclose(policy.observations[-1][12:15], zone)
    scene = {"hand": {**hand, "seen": False}, "zones": {"handoff": {"x": 0.3, "y": 0.0, "z": 0.12}}}
    pr.run_policy(FakeDriver(), lambda: scene, "unused.zip", timeout=he.DT, policy=policy)
    assert np.allclose(policy.observations[-1][12:15], [0.3, 0.0, 0.12])
    assert pr.target_point({"hand": {"x": "bad", "y": 0.0, "z": 0.0, "seen": True}}) == zone


