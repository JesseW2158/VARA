def test_render_video_writes_an_mp4_when_a_renderer_is_available(tmp_path, tiny_policy):
    from rl import render_video as rv

    env = he.HandoffEnv(render_mode="rgb_array")
    try:
        env.reset(seed=0)
        try:
            env.render()
        except Exception as exc:  # no OpenGL here: the renderer is never required by tests
            pytest.skip(f"no offscreen renderer on this machine: {exc}")
    finally:
        env.close()
    out = tmp_path / "clip.mp4"
    try:
        info = rv.render_video(tiny_policy, out, seconds=0.3, fps=30, seed=1)
    except rv.RendererUnavailable as exc:
        pytest.skip(str(exc))
    assert out.is_file() and out.stat().st_size > 0
    assert info["frames"] == 9 and info["width"] == 640 and info["height"] == 480 and info["out"] == str(out)
